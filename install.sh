  --dry-run           show what would be done, write nothing
  --list              show presets, themes and defaults
  -h, --help          this text
EOF
}

dflt() {
  case "$1" in
    PRESET) echo minimal ;;   KEYS) echo alt ;;       MOD) echo alt ;;
