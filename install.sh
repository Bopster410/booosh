  cat <<'EOF'
Usage: ./install.sh [options]

Presets
  --preset NAME       appearance: minimal | classic | borderless
  --keys NAME         keybinds:   alt | default
  --mod MODS          modifier for the 'alt' keybinds: alt | super | ctrl+alt ...
                      (flag only, not in the menu; default alt, e.g. super on a Mac)
Parameters
  --theme NAME        auto | mocha | rose-pine | kanagawa | tokyonight | gruvbox | nord
                      or any Ghostty theme name (ghostty +list-themes)
  --font FAMILY       font family (default: JetBrains Mono, built into Ghostty)
