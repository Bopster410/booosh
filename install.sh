#!/usr/bin/env bash
# boosh: terminal setup installer. The Ghostty config is GENERATED from an appearance preset,
# a keybind preset and a few parameters; everything else is symlinked.
#
#   ./install.sh                 interactive menu (when run in a terminal)
#   ./install.sh --yes           no questions: last saved choices, else defaults
#   ./install.sh --preset borderless --theme nord --font-size 15
#   ./install.sh --editor nano   pick the default editor (config is linked, EDITOR set in fish)
#   ./install.sh --only prompt   install just one part (ghostty, editor or prompt)
#   ./install.sh --list          show presets / themes / defaults
#   ./install.sh --cheatsheet    print the keybind cheatsheet for the chosen setup
#                                (a copy is also written to ~/.config/ghostty/cheatsheet.md)
#
# Precedence: flags > menu answers > last saved choices > defaults.
# Works with bash 3.2 (macOS system bash).
set -euo pipefail

SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
case "$(uname -s)" in
  Linux)  OS=linux ;;
  Darwin) OS=macos ;;
  *)      echo "unsupported OS: $(uname -s) (on Windows use WSL)" >&2; exit 1 ;;
esac

PRESETS="minimal classic borderless"
PROMPTS="boosh default"
KEYSETS="alt default"
THEMES="auto mocha rose-pine kanagawa tokyonight gruvbox nord custom"
CURSORS="block bar underline block_hollow"
VARS="PRESET KEYS MOD THEME FONT FONT_SIZE LIGATURES CURSOR BLINK OPACITY PROMPT EDITOR_NAME"

# editors/<name>/editor.conf makes <name> selectable; "none" installs no editor config
EDITORS=""
for d in "$SRC"/editors/*/; do
  [ -f "${d}editor.conf" ] && EDITORS="$EDITORS $(basename "$d")"
done
EDITORS="${EDITORS# } none"

GH="$HOME/.config/ghostty"
CHOICES="$GH/.install-choices"
MARKER="# GENERATED by boosh/install.sh"

die() { echo "error: $*" >&2; exit 1; }

# shellcheck source=lib/menu.sh
. "$SRC/lib/menu.sh"

editor_get() { sed -n "s/^$2=//p" "$SRC/editors/$1/editor.conf" | head -n 1; }

# one-line hints shown next to the options of the arrow-key menus
menu_desc() { # menu_desc VAR OPTION
  case "$1:$2" in
    PRESET:minimal)    echo "thin title bar with the working directory, tab bar at the bottom" ;;
    PRESET:classic)    echo "close to stock Ghostty" ;;
    PRESET:borderless) echo "no title bar and no frame" ;;
    KEYS:alt)          echo "adds short keys: Alt+arrows = split, Alt+T = new tab" ;;
    KEYS:default)      echo "stock keys only: Ctrl+Shift+O = split, Ctrl+Shift+T = new tab" ;;
    THEME:auto)        echo "Catppuccin, follows the system light/dark setting" ;;
    THEME:custom)      echo "any name from: ghostty +list-themes" ;;
    CURSOR:block)      echo "filled box, the classic terminal cursor" ;;
    CURSOR:bar)        echo "thin vertical line, like in text editors" ;;
    CURSOR:underline)  echo "a line under the character" ;;
    CURSOR:block_hollow) echo "outline of a box (shown when the window is unfocused)" ;;
    BLINK:yes)         echo "the cursor blinks" ;;
    BLINK:no)          echo "the cursor stays steady" ;;
    LIGATURES:yes)     echo "pairs like != -> => become one joined shape (the font must support it)" ;;
    LIGATURES:no)      echo "every character is drawn separately" ;;
    PROMPT:boosh)      echo "two lines, git status computed in the background, no plugin" ;;
    PROMPT:default)    echo "fish's own prompt, nothing is installed" ;;
    EDITOR_NAME:none)  echo "do not install an editor config" ;;
    EDITOR_NAME:*)     [ -f "$SRC/editors/$2/editor.conf" ] && editor_get "$2" DESCRIPTION || true ;;
  esac
}

theme_spec() { # theme_spec [KEY]  (default: the chosen $THEME) -> Ghostty "theme =" value
  local key="${1:-$THEME}"
  case "$key" in
    auto)       echo "light:Catppuccin Latte,dark:Catppuccin Mocha" ;;
    mocha)      echo "Catppuccin Mocha" ;;
    rose-pine)  echo "light:Rose Pine Dawn,dark:Rose Pine" ;;
    kanagawa)   echo "light:Kanagawa Lotus,dark:Kanagawa Wave" ;;
    tokyonight) echo "light:TokyoNight Day,dark:TokyoNight" ;;
    gruvbox)    echo "light:Gruvbox Light,dark:Gruvbox Dark" ;;
    nord)       echo "light:Nord Light,dark:Nord" ;;
    *)          echo "$key" ;;
  esac
}

# ─── theme preview (drawn under the theme menu) ──────────
# Reads Ghostty's own theme files and paints a small sample in 24-bit colour.
# The terminal itself is never recoloured.
THEME_DIRS=("$HOME/.config/ghostty/themes" "${GHOSTTY_RESOURCES_DIR:-/nonexistent}/themes"
  /usr/share/ghostty/themes /usr/local/share/ghostty/themes /opt/homebrew/share/ghostty/themes
  /home/linuxbrew/.linuxbrew/share/ghostty/themes /Applications/Ghostty.app/Contents/Resources/ghostty/themes)

theme_file() { # theme_file NAME -> path of the theme file
  local d
  for d in "${THEME_DIRS[@]}"; do
    if [ -f "$d/$1" ]; then echo "$d/$1"; return 0; fi
  done
  return 1
}

_tp_rgb() { local h="$1"; [ "$h" != - ] || h=808080; echo "$((16#${h:0:2})) $((16#${h:2:2})) $((16#${h:4:2}))"; }
_tp_bg()  { set -- $(_tp_rgb "$1"); printf '\033[48;2;%d;%d;%dm' "$1" "$2" "$3"; }
_tp_fg()  { set -- $(_tp_rgb "$1"); printf '\033[38;2;%d;%d;%dm' "$1" "$2" "$3"; }

theme_block() { # theme_block NAME -> 4 lines, each 34 columns wide
  local name="$1" f vals i R=$'\033[0m' base l1="" l2="" fgc c1 c2 c3 c4
  if ! f="$(theme_file "$name")"; then
    printf '%-34s\n%-34s\n%-34s\n%-34s\n' "theme file not found:" "$name" "(ghostty may still know it)" ""
    return 0
  fi
  read -r -a vals <<< "$(awk '
    /^background *=/ { v = $3; sub("#", "", v); bg = v }
    /^foreground *=/ { v = $3; sub("#", "", v); fg = v }
    /^palette *=/    { split($3, a, "="); v = a[2]; sub("#", "", v); p[a[1]] = v }
    END { printf "%s %s", (bg == "" ? "-" : bg), (fg == "" ? "-" : fg)
          for (i = 0; i < 16; i++) printf " %s", (p[i] == "" ? "-" : p[i])
          print "" }' "$f")"
  base="$(_tp_bg "${vals[0]}")$(_tp_fg "${vals[1]}")"
  for i in 2 3 4 5 6 7 8 9; do
    l1="$l1$(_tp_bg "${vals[$i]}")    $R"
    l2="$l2$(_tp_bg "${vals[$((i + 8))]}")    $R"
  done
  printf '%s%s  %s\n' "$l1" "$base" "$R"
  printf '%s%s  %s\n' "$l2" "$base" "$R"
  fgc="$(_tp_fg "${vals[1]}")"
  c1="$(_tp_fg "${vals[3]}")"; c2="$(_tp_fg "${vals[4]}")"; c3="$(_tp_fg "${vals[5]}")"; c4="$(_tp_fg "${vals[6]}")"
  printf '%s %s~/app%s main%s $ git diff%*s%s\n' "$base" "$c4" "$c2" "$fgc" 12 "" "$R"
  printf '%s %serror:%s cannot open %s%s%*s%s\n' "$base" "$c1" "$fgc" "$c3" "'file.txt'" 4 "" "$R"
}

_rep() { local s="" i; for ((i = 0; i < $2; i++)); do s="$s$1"; done; printf '%s' "$s"; }

_tp_box() { # _tp_box CAPTION NAME -> BOX[0..5]: the sample in a frame, caption in the top border
  local cap=" ${1:0:30} " name="$2" TL=┌ TR=┐ BL=└ BR=┘ H=─ V=│ line i=1
  local D=$'\033[90m' R=$'\033[0m'
  if ! _menu_utf8; then TL="+"; TR="+"; BL="+"; BR="+"; H="-"; V="|"; fi
  BOX=("$D$TL$H$cap$(_rep "$H" $((33 - ${#cap})))$TR$R")
  while IFS= read -r line; do BOX[$i]="$D$V$R$line$D$V$R"; i=$((i + 1)); done <<< "$(theme_block "$name")"
  BOX[5]="$D$BL$(_rep "$H" 34)$BR$R"
}

theme_preview() { # theme_preview KEY -> 6 lines: framed sample(s) with the theme name in the border
  local key="$1" spec dark light="" i cols _r
  case "${COLORTERM:-}" in truecolor|24bit) ;; *) echo "  (the colour preview needs a truecolor terminal)"; return 0 ;; esac
  if [ "$key" = custom ]; then echo "  type any name from: ghostty +list-themes"; return 0; fi
  spec="$(theme_spec "$key")"
  case "$spec" in
    light:*,dark:*) light="${spec#light:}"; light="${light%%,dark:*}"; dark="${spec#*,dark:}" ;;
    *)              dark="$spec" ;;
  esac
  read -r _r cols <<< "$(_menu_size)"
  local -a D=() L=()
  if [ -n "$light" ] && [ "$cols" -ge 78 ]; then
    _tp_box "dark: $dark" "$dark";   D=("${BOX[@]}")
    _tp_box "light: $light" "$light"; L=("${BOX[@]}")
    for i in 0 1 2 3 4 5; do printf '  %s  %s\n' "${D[$i]}" "${L[$i]}"; done
  else
    if [ -n "$light" ]; then _tp_box "dark: $dark" "$dark"; else _tp_box "theme: $dark" "$dark"; fi
    for i in 0 1 2 3 4 5; do printf '  %s\n' "${BOX[$i]}"; done
  fi
}

# ─── font family choices ─────────────────────────────────
FONT_DEFAULT="JetBrains Mono"
FONT_DEFAULT_LABEL="JetBrains Mono (built in)"
FONT_OTHER_LABEL="Other (type a name)"
FONT_LIST_MONO=0

font_curated() { # well-known coding fonts, offered first when they are installed
  printf '%s\n' "Fira Code" "Cascadia Code" "Cascadia Mono" "Source Code Pro" "Hack" "Iosevka" "Inconsolata" \
    "Ubuntu Mono" "DejaVu Sans Mono" "Liberation Mono" "Noto Sans Mono" "Menlo" "Monaco" "SF Mono" "Consolas" "Courier New"
}

installed_fonts() { # families installed on this machine, one per line (fontconfig: monospace only)
  if command -v fc-list >/dev/null 2>&1; then
    fc-list :spacing=mono family 2>/dev/null | sed 's/,.*//' | grep -viE 'emoji|signwriting|symbols|color|math|^$' | sort -u
  elif command -v ghostty >/dev/null 2>&1; then
    ghostty +list-fonts 2>/dev/null | grep -v '^[[:space:]]' | grep -v '^$' | sort -u
  fi
}

font_known() { # font_known NAME -> true if the family exists here (or we cannot tell)
  if command -v fc-list >/dev/null 2>&1; then [ -n "$(fc-list "$1" family 2>/dev/null)" ]
  elif command -v ghostty >/dev/null 2>&1; then ghostty +list-fonts 2>/dev/null | grep -ixqF "$1"
  else return 0; fi
}

font_options() { # fills FONT_OPTS: built-in default, installed coding fonts (max 9 in total), "Other"
  local all f
  all="$(installed_fonts)"
  if command -v fc-list >/dev/null 2>&1; then FONT_LIST_MONO=1; else FONT_LIST_MONO=0; fi   # list is monospace-only
  FONT_OPTS=("$FONT_DEFAULT_LABEL")
  while IFS= read -r f; do
    if [ "${#FONT_OPTS[@]}" -lt 9 ] && [ "$f" != "$FONT_DEFAULT" ] && grep -Fxq "$f" <<< "$all"; then FONT_OPTS[${#FONT_OPTS[@]}]="$f"; fi
  done <<< "$(font_curated)"
  if [ "$FONT_LIST_MONO" = 1 ]; then   # then other installed monospace families
    while IFS= read -r f; do
      [ -n "$f" ] && [ "$f" != "$FONT_DEFAULT" ] || continue
      case " ${FONT_OPTS[*]} " in *" $f "*) continue ;; esac
      if [ "${#FONT_OPTS[@]}" -lt 9 ]; then FONT_OPTS[${#FONT_OPTS[@]}]="$f"; fi
    done <<< "$all"
  fi
  FONT_OPTS[${#FONT_OPTS[@]}]="$FONT_OTHER_LABEL"
}

font_preview() { # font_preview OPTION -> 3 lines of facts (a terminal cannot draw glyphs of another font)
  local opt="$1" styles file
  case "$opt" in
    "$FONT_DEFAULT_LABEL")
      echo "  built into Ghostty, with Nerd Font symbols; identical on every machine"; echo "  the safe default" ;;
    "$FONT_OTHER_LABEL")
      echo "  type any installed family name"; echo "  empty or not found: falls back to $FONT_DEFAULT" ;;
    *)
      if command -v fc-list >/dev/null 2>&1; then
        styles="$(fc-list "$opt" style 2>/dev/null | sed 's/.*style=//; s/,.*//' | grep -v '^[[:space:]]*$' | sort -u | paste -sd, - | sed 's/,/, /g')"
        file="$(fc-list "$opt" file 2>/dev/null | head -n 1 | sed 's/: *$//')"
        echo "  styles: ${styles:-unknown}"; echo "  file: ${file:-unknown}"
      else
        echo "  installed on this machine"; echo "  (no further details without fontconfig)"
      fi ;;
  esac
  printf '  \033[2ma terminal cannot draw other fonts, so only details are shown\033[0m\n'
}

# ─── keybind preview: a few example keys ─────────────────
keys_preview() { # keys_preview OPTION -> 7 lines (built from the same data as the cheatsheet)
  local opt="$1" mod="${MOD:-$D_MOD}" custom="" stock="" have=0 rows head
  if [ "$opt" = alt ]; then
    custom="$(sed "s/@MOD@/$mod/g" "$SRC/ghostty/keys/alt.conf" | sed -n 's/^keybind = /c keybind = /p')"
    have=1; head="  with this preset (the stock keys keep working too):"
  else
    head="  stock Ghostty keys:"
  fi
  if command -v ghostty >/dev/null 2>&1; then
    stock="$(ghostty +list-keybinds --default 2>/dev/null | sed -n 's/^keybind = /s keybind = /p')"
  fi
  rows="$({ [ -z "$custom" ] || echo "$custom"; [ -z "$stock" ] || echo "$stock"; } \
    | awk -v haveCustom="$have" -f "$SRC/ghostty/cheatsheet.awk" \
    | awk -F'|' -v have="$have" '
        function trim(x) { gsub(/^[ \t]+|[ \t]+$/, "", x); return x }
        BEGIN {
          if (have) n = split("Split pane (arrow = direction)@split|Focus pane (arrow = direction)@focus pane|New tab@new tab|Previous tab@previous tab|Close pane (the last pane closes the tab)@close pane|Zoom / unzoom pane@zoom pane", T, "|")
          else      n = split("Split right@split right|Split down@split down|Focus pane (arrow = direction)@focus pane|New tab@new tab|Previous tab@previous tab|Close tab with all its panes@close tab", T, "|")
        }
        NF >= 3 {
          k = trim($3); gsub(/`/, "", k); split(k, a, ", "); k = a[1]
          if (k != "" && k != "—") R[trim($2)] = k
        }
        function dw(x,  t) { t = x; gsub(/↑|↓|←|→/, "x", t); return length(t) }   # arrows are 3 bytes but 1 column
        END { for (i = 1; i <= n; i++) { split(T[i], q, "@"); if (q[1] in R) { pad = 18 - dw(R[q[1]]); if (pad < 1) pad = 1; printf "  %s%*s%s\n", R[q[1]], pad, "", q[2] } } }')"
  if [ -z "$rows" ]; then echo "  (install ghostty to list its stock keys)"; return 0; fi
  printf '\033[2m%s\033[0m\n%s\n' "$head" "$rows"
}

# ─── ligatures: an illustration ──────────────────────────
lig_preview() { # lig_preview yes|no -> 3 lines
  local on=$'\033[1m' off=$'\033[2m' R=$'\033[0m' a b
  if ! _menu_utf8; then echo "  ligatures join pairs like != -> => into one glyph (illustration needs UTF-8)"; return 0; fi
  if [ "$1" = yes ]; then a="$off"; b="$on"; else a="$on"; b="$off"; fi
  printf '  %s%-18s !=   ->   =>   ===  >=   <=   ::%s\n' "$a" "as typed:" "$R"
  printf '  %s%-18s ≠    →    ⇒    ≡    ≥    ≤    ∷%s\n' "$b" "joined (approx.):" "$R"
  printf '  \033[2millustration only: the real look depends on the font\033[0m\n'
}

# ─── cursor and blinking: the real cursor, live ──────────
# Uses DECSCUSR (CSI Ps SP q), which Ghostty honours; the menu library resets it afterwards.
_cursor_state() { # _cursor_state VAR OPTION -> sets CS_STYLE and CS_BLINK for what is highlighted
  CS_STYLE="${CURSOR:-$D_CURSOR}"; CS_BLINK="${BLINK:-$D_BLINK}"
  case "$1" in
    CURSOR) CS_STYLE="$2" ;;
    BLINK)  CS_BLINK="$2" ;;
  esac
}

menu_cursor_info() { case "$1" in CURSOR|BLINK) echo "2 27" ;; esac; }   # mock line: 2 up from the bottom, column 27 (end of its text)

menu_cursor_shape() { # VAR OPTION -> DECSCUSR code; nothing = hide the real cursor
  _cursor_state "$1" "$2"
  case "$CS_STYLE" in
    block)     if [ "$CS_BLINK" = yes ]; then echo 1; else echo 2; fi ;;
    underline) if [ "$CS_BLINK" = yes ]; then echo 3; else echo 4; fi ;;
    bar)       if [ "$CS_BLINK" = yes ]; then echo 5; else echo 6; fi ;;
  esac
}

theme_colors() { # theme_colors KEY -> "BG FG" (hex) of the dark variant of the theme; defaults when unknown
  local spec dark f bg=1e1e2e fg=cdd6f4
  spec="$(theme_spec "$1")"
  case "$spec" in light:*,dark:*) dark="${spec#*,dark:}" ;; *) dark="$spec" ;; esac
  if f="$(theme_file "$dark")"; then
    read -r bg fg <<< "$(awk '/^background *=/ { v=$3; sub("#","",v); b=v } /^foreground *=/ { v=$3; sub("#","",v); c=v }
      END { print (b==""?"1e1e2e":b), (c==""?"cdd6f4":c) }' "$f")"
  fi
  echo "$bg $fg"
}

cursor_preview() { # cursor_preview VAR OPTION -> 3 lines; line 2 is a mock terminal line, the real cursor is parked at its end
  local box="□" bg fg band R=$'\033[0m' text=" ~/app main \$ git status" pad
  _menu_utf8 || box="[ ]"
  _cursor_state "$1" "$2"
  printf '  \033[2mlive: your real cursor, %s, %s\033[0m\n' "$CS_STYLE" "$([ "$CS_BLINK" = yes ] && echo blinking || echo steady)"
  [ "$CS_STYLE" != block_hollow ] || text="$text$box"
  pad=$((38 - ${#text})); [ "$pad" -ge 0 ] || pad=0
  case "${COLORTERM:-}" in
    truecolor|24bit)
      read -r bg fg <<< "$(theme_colors "${THEME:-$D_THEME}")"
      band="$(_tp_bg "$bg")$(_tp_fg "$fg")$text$(printf '%*s' "$pad" "")$R" ;;
    *) band="$text" ;;
  esac
  printf '  %s\n' "$band"
  case "$CS_STYLE" in
    block_hollow) printf '  \033[2mhollow block: drawn as a shape, no terminal command for it\033[0m\n' ;;
    *) if [ "$1" = BLINK ]; then printf '  \033[2mwatch the cursor: it blinks or stays steady\033[0m\n'
       else printf '  \033[2mblinking follows the next question (now: %s)\033[0m\n' "${BLINK:-$D_BLINK}"; fi ;;
  esac
}

# ─── opacity: an illustration of the blend ───────────────
opacity_preview() { # opacity_preview VAR VALUE -> 3 lines: wallpaper next to the terminal over it
  local val="$2" a bg fg x r g b wr wg wb out1 out2 w=26 ch t t1=" ~/app main \$ git diff" t2=" error: cannot open" R=$'\033[0m' fgc
  case "${COLORTERM:-}" in truecolor|24bit) ;; *) echo "  (the preview needs a truecolor terminal)"; return 0 ;; esac
  a="$(_sl_h "$val")"; [ "$a" -gt 0 ] || return 0
  read -r bg fg <<< "$(theme_colors "${THEME:-$D_THEME}")"
  local bgr=$((16#${bg:0:2})) bgg=$((16#${bg:2:2})) bgb=$((16#${bg:4:2}))
  fgc="$(_tp_fg "$fg")"
  printf '  \033[2m%-*s%s\033[0m\n' $((w + 2)) "desktop behind" "terminal at $val over it"
  for t in 1 2; do
    out1=""; out2=""
    for ((x = 0; x < w; x++)); do
      wr=$((47 + (236 - 47) * x / (w - 1))); wg=$((111 + (140 - 111) * x / (w - 1))); wb=$((201 + (60 - 201) * x / (w - 1)))
      out1="$out1\033[48;2;${wr};${wg};${wb}m "
      r=$(( (a * bgr + (100 - a) * wr) / 100 )); g=$(( (a * bgg + (100 - a) * wg) / 100 )); b=$(( (a * bgb + (100 - a) * wb) / 100 ))
      if [ "$t" = 1 ]; then ch="${t1:$x:1}"; else ch="${t2:$x:1}"; fi
      [ -n "$ch" ] || ch=" "
      out2="$out2\033[48;2;${r};${g};${b}m$fgc$ch"
    done
    printf '  %b%b  %b%b\n' "$out1" "$R" "$out2" "$R"
  done
}

# ─── prompt preview: a static sample ─────────────────────
prompt_preview() { # prompt_preview OPTION -> 3 lines
  local R=$'\033[0m' D=$'\033[2m'
  local up="⇡" sym="❯" box="►"
  _menu_utf8 || { up="^"; sym=">"; box=">"; }
  case "$1" in
    boosh)
      printf '  \033[1;34m~/app\033[0m \033[32mmain\033[0m \033[36m%s1\033[0m \033[32m+2\033[0m \033[33m!1\033[0m \033[34m?3\033[0m \033[33m5s\033[0m\n' "$up"
      printf '  \033[35m%s\033[0m\n' "$sym"
      printf '  %sgit info appears a moment after the prompt; its look is one function%s\n' "$D" "$R" ;;
    *)
      printf '  \033[1;34m~/app\033[0m \033[32m(main)\033[0m%s\n' "$box"
      printf '\n'
      printf '  %sfish own prompt: one line, git is checked before every prompt%s\n' "$D" "$R" ;;
  esac
}

