ask_choice() { # ask_choice VAR "label" opt...  (arrow menu on a terminal, numbered prompt otherwise)
  local var="$1" label="$2"; shift 2
  local d="D_$var" def o found=0
  def="${!d}"
  for o in "$@"; do [ "$o" = "$def" ] && found=1; done
  # a saved value that is not a built-in option (e.g. a custom theme) is offered first
  if [ "$found" = 0 ] && [ -n "$def" ]; then set -- "$def" "$@"; fi
  if menu_ok; then select_menu "$var" "$label" "$def" "$@"; else ask_choice_plain "$var" "$label" "$@"; fi
}

ask_choice_plain() {
  local var="$1" label="$2"; shift 2
  local d="D_$var" def i ans o
  def="${!d}"
  echo; echo "$label"
  i=1
  for o in "$@"; do
    if [ "$o" = "$def" ]; then printf '  * %d) %s\n' "$i" "$o"; else printf '    %d) %s\n' "$i" "$o"; fi
    i=$((i + 1))
  done
  while :; do
    printf '  choice [%s]: ' "$def"
    read -r ans || ans=""
    ans="${ans:-$def}"
    case "$ans" in
      ''|*[!0-9]*) ;;
      *) i=1; for o in "$@"; do [ "$i" = "$ans" ] && ans="$o"; i=$((i + 1)); done ;;
    esac
    for o in "$@"; do
      if [ "$o" = "$ans" ]; then printf -v "$var" '%s' "$ans"; return 0; fi
    done
    echo "  unknown choice: $ans"
  done
}

ask_text() { # ask_text VAR "label"
  local var="$1" label="$2" d="D_$1" def ans
  def="${!d}"
  printf '\n%s [%s]: ' "$label" "$def"
  read -r ans || ans=""
  printf -v "$var" '%s' "${ans:-$def}"
}

ask_yn() { # ask_yn VAR "label"  (arrow menu on a terminal, typed answer otherwise)
  local var="$1" label="$2" d="D_$1" def ans
  def="${!d}"
  if menu_ok; then select_menu "$var" "$label" "$def" yes no; return 0; fi
  while :; do
    printf '\n%s (yes/no) [%s]: ' "$label" "$def"
    read -r ans || ans=""
    ans="${ans:-$def}"
    case "$ans" in
      y|yes) printf -v "$var" '%s' yes; return 0 ;;
      n|no)  printf -v "$var" '%s' no;  return 0 ;;
    esac
    echo "  answer yes or no"
  done
}

