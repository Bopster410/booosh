#!/usr/bin/env bash
# Smoke tests for boosh. Everything runs against a throw-away $HOME; nothing outside it is touched.
#   bash tests/smoke.sh            # run all
# Needs: bash, git, awk, sed. `ghostty` and `fish` are optional (checks that need them are skipped).
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PASS=0; FAIL=0
pass() { PASS=$((PASS + 1)); printf '  ok    %s\n' "$1"; }
fail() { FAIL=$((FAIL + 1)); printf '  FAIL  %s\n' "$1"; [ -z "${2:-}" ] || printf '        %s\n' "$2"; }
check() { # check "name" command...   (passes when the command succeeds)
  local name="$1"; shift
  if "$@" >/dev/null 2>&1; then pass "$name"; else fail "$name"; fi
}
has() { grep -qE -- "$2" <<< "$1"; }   # has "$text" "regex"

new_home() { T="$(mktemp -d "${TMPDIR:-/tmp}/boosh-test.XXXXXX")"; export HOME="$T" XDG_CONFIG_HOME="$T/.config"; unset GIT_CONFIG_GLOBAL; }
cleanup() { [ -z "${T:-}" ] || rm -rf "$T"; }
trap cleanup EXIT

echo "== syntax"
for f in install.sh pack bootstrap.sh lib/menu.sh tests/smoke.sh; do check "bash -n $f" bash -n "$ROOT/$f"; done

echo "== install.sh"
new_home
out="$("$ROOT/install.sh" --list)"
has "$out" "minimal classic borderless" && pass "--list shows appearance presets" || fail "--list shows appearance presets"
has "$out" "nano vim none" && pass "--list shows editors" || fail "--list shows editors"

out="$("$ROOT/install.sh" --yes --no-cheatsheet 2>&1)"
CFG="$HOME/.config/ghostty/config"
check "default install writes the generated config" test -f "$CFG"
check "generated config carries the marker" grep -q "^# GENERATED by boosh/install.sh" "$CFG"
check "default theme is the light/dark pair" grep -q "^theme = light:Catppuccin Latte,dark:Catppuccin Mocha" "$CFG"
check "alt keybinds are present" grep -q "^keybind = alt+key_t=new_tab" "$CFG"
check "local.conf is linked" test -L "$HOME/.config/ghostty/local.conf"
check ".vimrc is linked" test -L "$HOME/.vimrc"
check "fish snippet sets EDITOR=vim" grep -q "^set -gx EDITOR vim" "$HOME/.config/fish/conf.d/00-boosh-core.fish"
check "saved choices file exists" test -f "$HOME/.config/ghostty/.install-choices"
out="$("$ROOT/install.sh" --yes --no-cheatsheet 2>&1)"
has "$out" "unchanged" && pass "second run changes nothing" || fail "second run changes nothing" "$out"

out="$("$ROOT/install.sh" --yes --no-cheatsheet --preset borderless --keys default --theme nord --font-size 15 --cursor bar --blink --ligatures --opacity 0.9 2>&1)"
check "borderless preset applies" grep -q "^window-decoration = none" "$CFG"
check "default keys drop the alt binds" bash -c "! grep -q '^keybind = alt+' '$CFG'"
check "named theme maps to its pair" grep -q "^theme = light:Nord Light,dark:Nord" "$CFG"
check "font size flag" grep -q "^font-size = 15" "$CFG"
check "cursor and blink flags" bash -c "grep -q '^cursor-style = bar' '$CFG' && grep -q '^cursor-style-blink = true' '$CFG'"
check "ligatures flag leaves calt alone" bash -c "! grep -q 'font-feature = -calt' '$CFG'"
check "opacity flag" grep -q "^background-opacity = 0.9" "$CFG"
"$ROOT/install.sh" --yes --no-cheatsheet --mod super --keys alt >/dev/null 2>&1
check "--mod super rewrites the binds" grep -q "^keybind = super+key_t=new_tab" "$CFG"

"$ROOT/install.sh" --yes --no-cheatsheet --editor nano >/dev/null 2>&1
check "nano editor links .nanorc" test -L "$HOME/.nanorc"
check "EDITOR switches to nano" grep -q "^set -gx EDITOR nano" "$HOME/.config/fish/conf.d/00-boosh-core.fish"
"$ROOT/install.sh" --yes --no-cheatsheet --editor none >/dev/null 2>&1
check "editor none removes the fish snippet" test ! -e "$HOME/.config/fish/conf.d/00-boosh-core.fish"

for bad in "--preset nope" "--opacity 2" "--font-size big" "--cursor wide" "--mod shift" "--theme custom" "--bogus"; do
  # shellcheck disable=SC2086
  if "$ROOT/install.sh" --yes --dry-run $bad >/dev/null 2>&1; then fail "rejects $bad"; else pass "rejects $bad"; fi
done

snapshot() { { find "$HOME" \( -type f -o -type l \) | sort; find "$HOME" -type f | sort | xargs cat | cksum; } 2>/dev/null; }
before="$(snapshot)"
"$ROOT/install.sh" --yes --dry-run --preset classic --editor nano >/dev/null 2>&1
after="$(snapshot)"
[ "$before" = "$after" ] && pass "--dry-run writes nothing" || fail "--dry-run writes nothing"

out="$("$ROOT/install.sh" --print --preset classic)"
has "$out" "window-decoration = auto" && pass "--print shows the config without writing" || fail "--print shows the config without writing"

echo "== cheatsheet"
out="$("$ROOT/install.sh" --cheatsheet --mod alt --keys alt)"
has "$out" "^# Ghostty cheatsheet" && pass "--cheatsheet prints markdown" || fail "--cheatsheet prints markdown"
has "$out" 'Alt\+T' && pass "cheatsheet lists the alt binds" || fail "cheatsheet lists the alt binds"
has "$out" 'Alt\+↑↓←→' && pass "arrow binds are collapsed to one row" || fail "arrow binds are collapsed to one row"
out="$("$ROOT/install.sh" --cheatsheet --mod super --keys alt)"
has "$out" 'Super\+T' && pass "cheatsheet follows --mod" || fail "cheatsheet follows --mod"

echo "== pack"
cleanup; new_home
git config --global user.name test >/dev/null 2>&1 || true
out="$("$ROOT/pack" list)"
has "$out" "git +available" && has "$out" "docker +available" && pass "pack list" || fail "pack list" "$out"
out="$("$ROOT/pack" show git)"
has "$out" "gst +=" && pass "pack show lists abbreviations" || fail "pack show lists abbreviations"

"$ROOT/pack" add git --no-tools >/dev/null 2>&1
check "git pack links the fish snippet" test -L "$HOME/.config/fish/conf.d/pack-git.fish"
check "git pack links the git config" test -L "$HOME/.config/git/pack-git.conf"
check "git include.path is set" bash -c "git config --global --get-all include.path | grep -qx '~/.config/git/pack-git.conf'"
check "git settings take effect" bash -c "[ \"\$(git config --get push.autosetupremote)\" = true ]"
check "pack status is healthy" "$ROOT/pack" status
out="$("$ROOT/pack" add git --no-tools 2>&1)"
has "$out" "ok +include.path" && pass "pack add is idempotent" || fail "pack add is idempotent" "$out"

# delta only while the command exists
mkdir -p "$HOME/bin"; printf '#!/bin/sh\ncat\n' > "$HOME/bin/delta"; chmod +x "$HOME/bin/delta"
PATH="$HOME/bin:$PATH" "$ROOT/pack" add git --no-tools >/dev/null 2>&1
check "delta config is included while delta exists" bash -c "PATH='$HOME/bin:$PATH' git config --get core.pager | grep -qx delta"
if "$ROOT/pack" status >/dev/null 2>&1; then fail "status warns when delta disappears"; else pass "status warns when delta disappears"; fi
"$ROOT/pack" add git --no-tools >/dev/null 2>&1
check "re-adding switches the delta config off" bash -c "! git config --get core.pager"

"$ROOT/pack" remove git >/dev/null 2>&1
check "remove unlinks the fish snippet" test ! -e "$HOME/.config/fish/conf.d/pack-git.fish"
check "remove drops the include" bash -c "! git config --global --get-all include.path | grep -q pack-git"

# a value the user already set must not be overridden silently
git config --global push.autoSetupRemote false
out="$("$ROOT/pack" add git --no-tools 2>&1)"
has "$out" "yours=false" && pass "conflicting git setting is reported" || fail "conflicting git setting is reported"
check "...and left alone without --yes" bash -c "[ \"\$(git config --get push.autosetupremote)\" = false ]"
"$ROOT/pack" add git --no-tools --yes >/dev/null 2>&1
check "--yes lets the pack win" bash -c "[ \"\$(git config --get push.autosetupremote)\" = true ]"

# foreign files are backed up / left alone
rm -f "$HOME/.config/fish/conf.d/pack-docker.fish"; mkdir -p "$HOME/.config/fish/conf.d"; echo mine > "$HOME/.config/fish/conf.d/pack-docker.fish"
"$ROOT/pack" add docker --no-tools >/dev/null 2>&1
check "an existing file is backed up" test -f "$HOME/.config/fish/conf.d/pack-docker.fish.bak"
check "docker pack links its snippet" test -L "$HOME/.config/fish/conf.d/pack-docker.fish"

echo "== fish snippets"
if command -v fish >/dev/null 2>&1; then
  for p in git docker; do
    out="$(fish --no-config -i -c "source '$ROOT/packs/$p/fish.fish'; abbr --show" 2>&1)"
    if [ -n "$out" ] && ! has "$out" "error|Error"; then pass "$p snippet loads and defines abbreviations"; else fail "$p snippet loads and defines abbreviations" "$out"; fi
  done
else
  echo "  skip  fish is not installed"
fi

echo "== menu library (needs a pty; set BOOSH_TEST_PTY=1 on Linux to run)"
if [ "${BOOSH_TEST_PTY:-0}" = 1 ] && command -v script >/dev/null 2>&1; then
  cat > "$HOME/menu-test.sh" <<EOF
#!/usr/bin/env bash
source "$ROOT/lib/menu.sh"
select_menu PICK "Pick:" a a b c
select_slider SZ "Size:" 8 32 0.5 13
echo "RESULT=\$PICK/\$SZ"
EOF
  chmod +x "$HOME/menu-test.sh"
  out="$( { sleep 0.5; printf '\033[B\033[B\n'; sleep 0.5; printf '\033[C\033[C\n'; sleep 0.5; } | script -qec "$HOME/menu-test.sh" /dev/null 2>&1 | tr -d '\r')"
  has "$out" "RESULT=c/14" && pass "arrow keys drive the menu and the slider" || fail "arrow keys drive the menu and the slider" "$out"
else
  echo "  skip"
fi

echo
echo "passed: $PASS, failed: $FAIL"
[ "$FAIL" -eq 0 ]
